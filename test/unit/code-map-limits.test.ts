// The Codebase Map's index holds up against files that are hard to read (docs/audit.md, third pass):
// each file's parse and query have a time limit, a file the parser fails on is on the map by name
// only, and a file too large to parse is read only as far as its header.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import type { FileFacts } from '../../src/core/codemap/facts';
import { CodeParser, TOO_DEEP, TOO_LONG } from '../../src/extension/code-parser';
import { FactsCache, MAX_FILE_BYTES, indexFolder } from '../../src/extension/code-indexer';
import { ParseService } from '../../src/extension/parse-service';
import { repoRoot } from './helpers';

const grammarDir = path.join(repoRoot, 'grammars');
// Parses in milliseconds; the query took 40 to 70 seconds on it without a time limit.
const UNCLOSED = '('.repeat(200000);

function folder(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vgraph-map-limits-'));
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), text);
  return dir;
}

class MemoryCache implements FactsCache {
  readonly entries = new Map<string, FileFacts>();
  get(p: string, hash: string): FileFacts | undefined {
    return this.entries.get(`${p}:${hash}`);
  }
  set(p: string, hash: string, facts: FileFacts): void {
    this.entries.set(`${p}:${hash}`, facts);
  }
}

describe('the parser has a time limit', () => {
  let parser: CodeParser;
  before(async () => {
    parser = await CodeParser.create(grammarDir);
  });
  after(() => parser.dispose());

  for (const grammar of ['javascript', 'python', 'rust'] as const) {
    test(`${grammar}: a file the query would take a minute on stops at the limit`, async () => {
      const started = Date.now();
      await assert.rejects(parser.facts(grammar, UNCLOSED), { message: TOO_LONG });
      assert.ok(Date.now() - started < 10000, `${Date.now() - started} ms`);
    });
  }

  test('the control flow of code nested too deeply says so', async () => {
    const deep = `function f() { x = ${'['.repeat(100000)}${']'.repeat(100000)}; }`;
    await assert.rejects(parser.flow('javascript', deep, 1), { message: TOO_DEEP });
  });
});

describe('the index with files that are hard to read', () => {
  let service: ParseService;
  before(() => {
    service = new ParseService(grammarDir);
  });
  after(() => service.dispose());

  test("a file that takes too long is on the map by name, until it changes; the others are read", async () => {
    const root = folder({ 'ok.js': 'export function fine() { return 1; }\n', 'slow.js': UNCLOSED });
    const cache = new MemoryCache();
    const started = Date.now();
    const cold = await indexFolder(root, { parser: service, cache });
    assert.ok(Date.now() - started < 15000, `${Date.now() - started} ms`);
    assert.ok(cold.index.entities.some((e) => e.kind === 'function' && e.name === 'fine' && e.path === 'ok.js'));
    assert.ok(cold.index.entities.some((e) => e.id === 'f:slow.js'), 'slow.js is on the map');
    assert.equal(cold.failed, 0);
    const warm = await indexFolder(root, { parser: service, cache });
    assert.equal(warm.parsed, 0, 'neither is read again');
  });

  test("a file the parser fails on is by name only, and doesn't fail the map", async () => {
    const root = folder({ 'ok.js': 'export function fine() { return 1; }\n', 'bad.js': 'export function broken() {}\n' });
    const failing = {
      facts: (grammar: string, text: string) => (text.includes('broken') ? Promise.reject(new Error('The parsing worker stopped.')) : service.facts(grammar as 'javascript', text))
    } as unknown as ParseService;
    const cache = new MemoryCache();
    const result = await indexFolder(root, { parser: failing, cache });
    assert.equal(result.failed, 1);
    assert.ok(result.index.entities.some((e) => e.name === 'fine'));
    assert.ok(result.index.entities.some((e) => e.id === 'f:bad.js') && !result.index.entities.some((e) => e.name === 'broken'));
    assert.equal(cache.entries.size, 1, "a failure isn't kept: the file is read again next time");
  });

  test('a file too large to parse is read only as far as its header', async () => {
    const header = '// Generated by NodeCraft from big.vgraph.\n';
    const root = folder({ 'big.vgraph.js': header + 'x;\n'.repeat(MAX_FILE_BYTES / 2) });
    const result = await indexFolder(root, { parser: service });
    assert.ok(result.index.generated.some((g) => g.path === 'big.vgraph.js'), JSON.stringify(result.index.generated));
    assert.equal(result.parsed, 0);
  });
});
