describe('tsconfig coverage', () => {
  test('default include covers everything except excluded folders', () => {
    const dir = project({ 'tsconfig.json': '{ // comment\n "compilerOptions": { "outDir": "dist", }, }' });
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'src/a.vgraph.ts')), true);
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'dist/a.vgraph.ts')), false);
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'node_modules/x/a.ts')), false);
  });

  test('include folders and globs', () => {
    const dir = project({ 'tsconfig.json': '{"include": ["src", "tools/*.ts"]}' });
    const covers = (f: string) => configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, f));
    assert.equal(covers('src/deep/a.vgraph.ts'), true);
    assert.equal(covers('tools/a.vgraph.ts'), true);
    assert.equal(covers('tools/nested/a.vgraph.ts'), false);
    assert.equal(covers('graphs/a.vgraph.ts'), false);
  });

  test('a config that only lists files covers nothing else', () => {
    const dir = project({ 'tsconfig.json': '{"files": ["main.ts"]}' });
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'a.vgraph.ts')), false);
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'main.ts')), true);
  });

  test('is undecided when the file list comes from extends', () => {
    const dir = project({ 'tsconfig.json': '{"extends": "./base.json"}' });
    assert.equal(configCovers(path.join(dir, 'tsconfig.json'), path.join(dir, 'a.vgraph.ts')), undefined);
  });

  test('globToRegExp', () => {
    assert.equal(globToRegExp('src/**/*.ts').test('src/a/b/c.ts'), true);
    assert.equal(globToRegExp('src/**/*.ts').test('src/c.ts'), true);
    assert.equal(globToRegExp('src/*.ts').test('src/a/c.ts'), false);
    assert.equal(globToRegExp('dist', true).test('dist/a.ts'), true);
  });
});

describe('verifyPlacement', () => {
  test('warns when tsconfig.json does not include the generated file', () => {
    const dir = project({ 'tsconfig.json': '{"include": ["src"]}' });
    const warnings = verifyPlacement('typescript', path.join(dir, 'graphs/a.vgraph.ts'), dir);
    assert.deepEqual(warnings.map((w) => w.code), ['output-outside-config']);
    assert.match(warnings[0].message, /isn't included by tsconfig\.json/);
    assert.deepEqual(verifyPlacement('typescript', path.join(dir, 'src/a.vgraph.ts'), dir), []);
  });

  test('says nothing without a tsconfig.json', () => {
    assert.deepEqual(verifyPlacement('typescript', path.join(project({}), 'a.vgraph.ts'), root), []);
  });

  test('warns when a Python module sits in a folder that is not a valid package name', () => {
    const dir = project({ 'pyproject.toml': '' });
    assert.deepEqual(verifyPlacement('python', path.join(dir, 'game_logic/a_vgraph.py'), dir), []);
    const warnings = verifyPlacement('python', path.join(dir, 'visual-nodes/a_vgraph.py'), dir);
    assert.deepEqual(warnings.map((w) => w.code), ['python-not-importable']);
    assert.match(warnings[0].message, /"visual-nodes"/);
  });
});

