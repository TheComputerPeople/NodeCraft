const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vgraph-placement-'));
after(() => fs.rmSync(root, { recursive: true, force: true }));

// Creates files under a fresh project folder; returns the folder.
function project(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(root, 'p-'));
  for (const [name, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
    fs.writeFileSync(path.join(dir, name), content);
  }
  return dir;
}

describe('generated file headers', () => {
  test('name the source graph', () => {
    assert.equal(generatedFrom('// Generated by Blueprint Visual Scripting from demo.vgraph.\n// Do not edit'), 'demo.vgraph');
    assert.equal(generatedFrom('# Generated by Blueprint Visual Scripting from my graph.vgraph.\r\n'), 'my graph.vgraph');
    assert.equal(generatedFrom('export const x = 1;\n'), undefined);
    assert.equal(generatedFrom('-- Generated by Blueprint Visual Scripting from a.vgraph.\n'), 'a.vgraph');
    assert.equal(generatedFrom('// Code generated by Blueprint Visual Scripting from a.vgraph. DO NOT EDIT.\n'), 'a.vgraph');
    assert.equal(generatedFrom('<?php\n// Generated by Blueprint Visual Scripting from a.vgraph.\n'), 'a.vgraph');  });

  test('isGeneratedFrom checks the file on disk', () => {
    const dir = project({ 'a.vgraph.ts': '// Generated by Blueprint Visual Scripting from a.vgraph.\n', 'mine.ts': 'export {};\n' });
    assert.equal(isGeneratedFrom(path.join(dir, 'a.vgraph.ts'), 'a.vgraph'), true);
    assert.equal(isGeneratedFrom(path.join(dir, 'a.vgraph.ts'), 'b.vgraph'), false);
    assert.equal(isGeneratedFrom(path.join(dir, 'mine.ts'), 'a.vgraph'), false);
    assert.equal(isGeneratedFrom(path.join(dir, 'missing.ts'), 'a.vgraph'), false);
  });

  // Renaming and deleting a graph, and removing stale outputs, find its files by the header.
  test('every language\'s generated files are recognized, test files too', () => {
    const graph = doc([node('s', 'core:event.start'), node('p', 'core:console.print', { 'pin:value': 'hi' }), node('t', 'core:test.case', { name: 'Says hi' })], [wire('s', 'execOut', 'p', 'execIn')]);
    for (const pack of builtinLanguagePacks().all()) {
      const result = compileDocument({ ...graph, name: 'Hello', language: pack.id }, { registry: new NodeRegistry(), languages: builtinLanguagePacks(), generate: { sourceFileName: 'Hello World.vgraph', outputDir: 'game', namespace: 'Game' } });
      assert.deepEqual(result.diagnostics.filter((d) => d.severity === 'error'), [], pack.id);
      const output = result.output!;
      // Not the support code beside them (companion files), which graphs share.
      for (const file of [output, ...(output.testFile ? [{ fileName: 'its test file', text: output.testFile }] : [])]) {
        assert.equal(generatedFrom(file.text), 'Hello World.vgraph', `${pack.id}: ${file.fileName} begins ${JSON.stringify(file.text.split('\n').slice(0, 3))}`);
      }
    }
  });
});

describe('detectModuleFormat', () => {
  test('follows the nearest package.json, as Node does', () => {
    const dir = project({ 'package.json': '{"type":"module"}', 'cjs/package.json': '{"name":"inner"}', 'cjs/graphs/x.vgraph': '' });
    assert.equal(detectModuleFormat(path.join(dir, 'graphs'), dir), 'esm');
    assert.equal(detectModuleFormat(path.join(dir, 'cjs/graphs'), dir), 'commonjs');
  });

  test('uses ES modules when there is no package.json', () => {
    const dir = project({ 'graphs/x.vgraph': '' });
    assert.equal(detectModuleFormat(path.join(dir, 'graphs'), dir), 'esm');
  });
});

describe('imports of project code', () => {
  test('TypeScript import extensions follow tsconfig.json', () => {
    const graphs = (config?: unknown, base?: unknown) => {
      const files: Record<string, string> = { 'graphs/x.vgraph': '' };
      if (config) files['tsconfig.json'] = JSON.stringify(config);
      if (base) files['tsconfig.base.json'] = JSON.stringify(base);
      const dir = project(files);
      return detectImportExtension(path.join(dir, 'graphs'), dir);
    };
    assert.equal(graphs(), 'ts', 'no tsconfig.json: Node.js runs .ts imports');
    assert.equal(graphs({ compilerOptions: { allowImportingTsExtensions: true } }), 'ts');
    assert.equal(graphs({ compilerOptions: { rewriteRelativeImportExtensions: true } }), 'ts');
    assert.equal(graphs({ compilerOptions: { module: 'nodenext' } }), 'js');
    assert.equal(graphs({ compilerOptions: { moduleResolution: 'Node16' } }), 'js');
    assert.equal(graphs({ compilerOptions: { moduleResolution: 'bundler' } }), 'none');
    assert.equal(graphs({ extends: './tsconfig.base.json' }, { compilerOptions: { module: 'NodeNext' } }), 'js', 'follows extends');
    assert.equal(graphs({ extends: './tsconfig.base', compilerOptions: { moduleResolution: 'bundler' } }, { compilerOptions: { module: 'nodenext' } }), 'none', 'own options win');
  });

  test('Python module names and import roots follow packages', () => {
    const dir = project({ 'src/game/__init__.py': '', 'src/game/combat.py': '', 'src/game/ai/__init__.py': '', 'src/game/ai/brain.py': '', 'scripts/tools.py': '' });
    assert.deepEqual(pythonModule(path.join(dir, 'src/game/combat.py'), dir), { module: 'game.combat', root: path.join(dir, 'src') });
    assert.deepEqual(pythonModule(path.join(dir, 'src/game/ai/brain.py'), dir), { module: 'game.ai.brain', root: path.join(dir, 'src') });
    assert.deepEqual(pythonModule(path.join(dir, 'src/game/__init__.py'), dir), { module: 'game', root: path.join(dir, 'src') });
    assert.deepEqual(pythonModule(path.join(dir, 'scripts/tools.py'), dir), { module: 'tools', root: path.join(dir, 'scripts') });
  });
});

describe('Rust modules', () => {
  test("follow the crate's src folder", () => {
    const dir = project({ 'Cargo.toml': '[package]', 'src/main.rs': '', 'src/game/mod.rs': '', 'src/game/combat.rs': '', 'tools/x.rs': '' });
    assert.equal(rustModule(path.join(dir, 'src/main.rs'), dir), '');
    assert.equal(rustModule(path.join(dir, 'src/game/mod.rs'), dir), 'game');
    assert.equal(rustModule(path.join(dir, 'src/game/combat.rs'), dir), 'game::combat');
    assert.equal(rustModule(path.join(dir, 'tools/x.rs'), dir), undefined, 'outside src');
    const loose = project({ 'a.rs': '' });
    assert.equal(rustModule(path.join(loose, 'a.rs'), loose), undefined, 'not in a crate');
  });

  test("Run builds the generated modules a graph uses, in turn, and the crate's modules when it calls them", () => {
    const dir = project({
      'Cargo.toml': '[package]',
      'src/main.rs': 'mod game;\npub(crate) mod util;\n// vgraph:begin (managed by Blueprint Visual Scripting)\npub mod vgraph_runtime;\n#[path = "graphs/duel_vgraph.rs"]\npub mod duel_vgraph;\n// vgraph:end\nfn main() {}\n',
      'src/game/combat.rs': '',
      'src/graphs/duel_vgraph.rs': 'crate::fighter_vgraph::Fighter::new(); crate::game::combat::damage(1.0)',
      'src/graphs/fighter_vgraph.rs': 'crate::stats_vgraph::Stats::new()',
      'src/graphs/stats_vgraph.rs': '',
      'src/graphs/unused_vgraph.rs': ''
    });
    const sources = rustRunSources(path.join(dir, 'src/graphs/duel_vgraph.rs'), dir, ['src/game/combat.rs']);
    assert.deepEqual(sources.generated, [path.join(dir, 'src/graphs/fighter_vgraph.rs'), path.join(dir, 'src/graphs/stats_vgraph.rs')]);
    assert.deepEqual(sources.crate, { src: path.join(dir, 'src'), modules: ['game', 'util'] }, 'not the generated modules');
    assert.equal(rustRunSources(path.join(dir, 'src/graphs/duel_vgraph.rs'), dir, []).crate, undefined, 'no project functions');
  });
});

describe('Java packages', () => {
  test('come from the folder under the Maven or Gradle source root', () => {
    const maven = project({ 'pom.xml': '<project></project>', 'src/main/java/game/graphs/x.vgraph': '', 'src/test/java/game/x.vgraph': '', 'tools/x.vgraph': '' });
    assert.deepEqual(javaProject(path.join(maven, 'src/main/java/game/graphs'), maven), { package: 'game.graphs', sourceRoots: [path.join(maven, 'src/main/java'), path.join(maven, 'src/test/java')], build: 'pom.xml' });
    assert.equal(javaProject(path.join(maven, 'src/test/java/game'), maven).package, 'game');
    assert.equal(javaProject(path.join(maven, 'src/main/java'), maven).package, undefined, 'the default package');
    assert.equal(javaProject(path.join(maven, 'tools'), maven).outside, true);
    const custom = project({ 'pom.xml': '<project><build><sourceDirectory>${project.basedir}/java</sourceDirectory></build></project>', 'java/app/x.vgraph': '' });
    assert.equal(javaProject(path.join(custom, 'java/app'), custom).package, 'app');
    const gradle = project({ 'build.gradle.kts': '', 'src/main/java/my-app/x.vgraph': '' });
    assert.equal(javaProject(path.join(gradle, 'src/main/java/my-app'), gradle).package, undefined, 'not a Java identifier');
    assert.deepEqual(javaProject(gradle, gradle).sourceRoots, [path.join(gradle, 'src/main/java')]);
    assert.deepEqual(javaProject(project({ 'x.vgraph': '' }), root), { sourceRoots: [] });
  });

  test('a graph outside the source roots gets a warning', () => {
    const dir = project({ 'pom.xml': '<project></project>', 'src/main/java/App.java': '', 'tools/Tool.java': '' });
    assert.match(verifyPlacement('java', path.join(dir, 'tools/Tool.java'), dir)[0].message, /isn't in a source folder of pom\.xml/);
    assert.deepEqual(verifyPlacement('java', path.join(dir, 'src/main/java/App.java'), dir), []);
  });
});

describe('Go packages', () => {
  test("follow the folder's other files, else its name; their import path is in the module", () => {
    const dir = project({ 'go.mod': 'module example.com/app\n', 'game/rules.go': '// Rules.\npackage rules\n', 'game/x_vgraph.go': 'package wrong\n', 'My-Tools/x.vgraph': '', 'cmd/main.go': 'package main\n' });
    assert.deepEqual(goPackage(path.join(dir, 'game'), dir), { name: 'rules', path: 'example.com/app/game', module: { path: 'example.com/app', dir } });
    assert.equal(goPackage(path.join(dir, 'My-Tools'), dir).name, 'mytools');
    assert.equal(goPackage(dir, dir).path, 'example.com/app');
    assert.deepEqual(goPackage(project({ 'x.vgraph': '' }), root).module, undefined, 'not in a module');
    assert.match(verifyPlacement('go', path.join(dir, 'cmd/x_vgraph.go'), dir)[0].message, /package main, which nothing can import/);
  });
});

