// Generated code and projects' checkers (docs/project-integration.md, part 3): type checkers run
// on it with the project's strictest settings, style linters skip it. The corpus of project layouts
// (test/conformance/corpus.test.ts) runs the checkers; these are the rules that make them pass.
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { compileDocument } from '../../src/core/compiler';
import { graphFileDefinitions } from '../../src/core/graph-files';
import { builtinLanguagePacks } from '../../src/core/languages';
import { NodeRegistry } from '../../src/core/registry';
import { parseDocument } from '../../src/core/serializer';
import { doc, node, repoRoot, wire } from './helpers';

const languages = builtinLanguagePacks();
const COUNTDOWN = ['Counter', 'Countdown', 'DoubleCounter', 'Levels', 'Shade'];

// The countdown sample (a class, its subclass, a structure and an enumeration) in `language`.
function countdown(language: string): Map<string, string> {
  const generator = languages.get(language)!.generator!;
  const docs = COUNTDOWN.map((name) => ({ name, doc: { ...parseDocument(fs.readFileSync(path.join(repoRoot, `sample/countdown/${name}.vgraph`), 'utf8'), name).document, language } }));
  const registry = new NodeRegistry();
  const module = (name: string) => (language === 'python' ? `countdown.${generator.outputFileName(`${name}.vgraph`).replace(/\.py$/, '')}` : language === 'csharp' || language === 'java' ? 'countdown' : undefined);
  for (const { name, doc: d } of docs) {
    const m = module(name);
    registry.registerMany(graphFileDefinitions(d, { document: `countdown/${name}.vgraph`, generatedPath: `countdown/${generator.outputFileName(`${name}.vgraph`)}`, ...(m ? { module: m } : {}) }, generator) ?? []);
  }
  return new Map(docs.map(({ name, doc: d }) => {
    const result = compileDocument(d, { registry, languages, generate: { sourceFileName: `${name}.vgraph`, outputDir: 'countdown', namespace: 'countdown', ...(language === 'python' ? { module: module(name) } : {}) } });
    assert.deepEqual(result.diagnostics.filter((x) => x.severity === 'error'), [], `${language} ${name}`);
    return [name, result.output!.text];
  }));
}

describe("generated code and projects' checkers", () => {
  test("style linters skip it: each language's marker, after the header's first line", () => {
    const markers: Record<string, string[]> = {
      typescript: ['/* eslint-disable */'], javascript: ['/* eslint-disable */'], python: ['# flake8: noqa', '# pylint: skip-file'], csharp: ['// <auto-generated/>']
    };
    for (const [language, lines] of Object.entries(markers)) {
      const text = countdown(language).get('Counter')!;
      assert.match(text, /^(\/\/|#) Generated by NodeCraft from Counter\.vgraph\.\n/, language);
      for (const line of lines) assert.ok(text.split('\n').slice(0, 5).includes(line), `${language}: ${line}`);
    }
  });

  test('a file imports only the types its code uses, not every type its parent class knows', () => {
    const doubled = (language: string) => countdown(language).get('DoubleCounter')!;
    assert.match(doubled('typescript'), /^import \{ Counter \} from "\.\/Counter\.vgraph\.ts";$/m);
    assert.doesNotMatch(doubled('typescript'), /import \{ (Levels|Shade) \}/);
    assert.match(doubled('python'), /^from countdown\.counter_vgraph import Counter$/m);
    assert.doesNotMatch(doubled('python'), /import (Levels|Shade)/);
    // A property named like a type (this.Second!.Levels) is no use of the type.
    assert.doesNotMatch(countdown('typescript').get('Countdown')!, /import \{ Levels \}/);
  });

  test("TypeScript marks what overrides the parent's (noImplicitOverride)", () => {
    assert.match(countdown('typescript').get('DoubleCounter')!, /^ {2}override stepSize\(\): number \{$/m);
    assert.match(countdown('typescript').get('Counter')!, /^ {2}stepSize\(\): number \{$/m);
  });

  test("a function whose every path returns gets no fallback return (it can't be reached)", () => {
    for (const language of ['typescript', 'python', 'csharp', 'java']) {
      const text = countdown(language).get('Counter')!;
      assert.doesNotMatch(text, /return \{ remaining: 0, emptied: false \}|return 0, False|return \(0L?, false\)|return new TakeResult\(0L, false\)/, language);
    }
  });

  test('Python truncates a float wired into an int, as C# and Java do', () => {
    assert.match(countdown('python').get('Counter')!, /Levels\(int\(self\._math_subtract\(self\.Levels\.amount, amount\)\), /);
    const d = doc([node('s', 'core:event.start'), node('set', 'core:variable.set', { variable: 'n', 'pin:value': 2.75 })], [wire('s', 'execOut', 'set', 'execIn')], [{ id: 'n', name: 'N', type: { id: 'int' } }]);
    const text = compileDocument({ ...d, language: 'python' }, { registry: new NodeRegistry(), languages, generate: { sourceFileName: 'T.vgraph' } }).output!.text;
    assert.match(text, /self\.N = 2$/m);
  });

  test("Java writes a whole number Add reads as a double, which -Xlint:cast doesn't call redundant", () => {
    const d = doc([node('s', 'core:event.start'), node('add', 'core:math.add', { 'pin:a': 1e21, 'pin:b': 0 }), node('p', 'core:console.print')],
      [wire('s', 'execOut', 'add', 'execIn'), wire('add', 'execOut', 'p', 'execIn'), wire('add', 'result', 'p', 'value')]);
    const text = compileDocument({ ...d, language: 'java' }, { registry: new NodeRegistry(), languages, generate: { sourceFileName: 'T.vgraph' } }).output!.text;
    assert.match(text, / = 1e\+21 \+ 0\.0;/);
    assert.doesNotMatch(text, /\(double\) 1e\+21/);
  });
});
